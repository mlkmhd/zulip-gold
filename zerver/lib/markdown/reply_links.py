import re
from collections.abc import Mapping

from zerver.lib.native_backend import load_native_contract

_rust_reply_links = load_native_contract("ZULIP_RUST_PLAIN_REPLY_LINKS", "MOBILE_REPLY_LINKS_API")


def needs_plain_reply_links(client_name: str | None) -> bool:
    native = getattr(_rust_reply_links, "mobile_client_needs_plain_reply_links", None)
    if native is not None:
        result = native(client_name)
        if result is not None:
            return result
    return client_name in {"ZulipFlutter", "ZulipMobile", "ZulipAndroid", "ZulipiOS"}


REPLY_LINK_RE = re.compile(r'<a class="message-reply-link" (href="[^"]*")>(.*?)</a>', re.DOTALL)
REPLY_LABEL_RE = re.compile(
    r'<strong class="message-reply-sender" dir="auto">(.*?)</strong>'
    r'<span class="message-reply-excerpt" dir="auto">(.*?)</span>',
    re.DOTALL,
)


_REFERENCE_REGEXES = REPLY_LINK_RE, REPLY_LABEL_RE


def render_plain_reply_links(html: str) -> str:
    # Match the markup generated by LinkInlineProcessor, preserving escaped
    # text and search highlights without reserializing the rest of the message.
    if 'class="message-reply-link"' not in html:
        return html

    native = getattr(_rust_reply_links, "render_mobile_plain_reply_links", None)
    if (
        native is not None
        and REPLY_LINK_RE is _REFERENCE_REGEXES[0]
        and REPLY_LABEL_RE is _REFERENCE_REGEXES[1]
    ):
        rendered = native(html)
        if rendered is not None:
            return rendered

    def replace_reply_link(match: re.Match[str]) -> str:
        href, label = match.groups()
        parts = REPLY_LABEL_RE.fullmatch(label)
        if parts is not None:
            sender, excerpt = parts.groups()
            label = f"{sender} · {excerpt}"
        return f"<a {href}>{label}</a>"

    return REPLY_LINK_RE.sub(replace_reply_link, html)


_REFERENCE_RENDERER = render_plain_reply_links


def uses_reference_reply_renderer() -> bool:
    return (
        render_plain_reply_links is _REFERENCE_RENDERER
        and REPLY_LINK_RE is _REFERENCE_REGEXES[0]
        and REPLY_LABEL_RE is _REFERENCE_REGEXES[1]
    )


def plain_reply_link_fields(data: Mapping[str, str | None], *fields: str) -> dict[str, str]:
    native = getattr(_rust_reply_links, "mobile_plain_reply_link_fields", None)
    if native is not None and uses_reference_reply_renderer():
        rendered = native(data, fields)
        if rendered is not None:
            return rendered
    return {
        field: render_plain_reply_links(html)
        for field in fields
        if (html := data.get(field)) is not None and 'class="message-reply-link"' in html
    }
