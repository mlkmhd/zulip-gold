import argparse
import re
import sys
import unicodedata
from pathlib import Path


def render() -> str:
    if sys.implementation.name != "cpython" or sys.version_info[:2] != (3, 12):
        raise RuntimeError("Generate autolink classes using the CPython 3.12 reference")
    ranges: list[tuple[int, int]] = []
    word = re.compile(r"\w")
    for point in range(0x110000):
        if 0xD800 <= point <= 0xDFFF or not word.fullmatch(chr(point)):
            continue
        if ranges and point == ranges[-1][1] + 1:
            ranges[-1] = (ranges[-1][0], point)
        else:
            ranges.append((point, point))
    lines = [
        "// Generated by rust-backend/tools/generate_markdown_autolink_data.py.",
        "// Python's word class differs from Rust regex's Unicode word class.",
        "",
        f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
        "",
        "pub(super) const WORD: &str = concat!(",
    ]
    # Keep spell-check exceptions on the exact generated Unicode ranges.
    false_positives = {0x0ABD, 0xAADD}
    for start, end in ranges:
        value = rf"\x{{{start:x}}}"
        if start != end:
            value += rf"-\x{{{end:x}}}"
        ignored = {start, end} & false_positives
        comment = ""
        if ignored:
            comment = " // codespell:ignore " + ",".join(f"{point:x}" for point in sorted(ignored))
        lines.append(f'    r"{value}",{comment}')
    lines.append(");")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate reference autolink Unicode classes offline."
    )
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "src/markdown_autolink_data.rs",
    )
    args = parser.parse_args()
    source = render()
    if args.check:
        if args.output.read_text() != source:
            parser.error("autolink classes differ; regenerate with the reference Python")
    else:
        args.output.write_text(source)


if __name__ == "__main__":
    main()
